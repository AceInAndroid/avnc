#!/usr/bin/env python3
"""Generate FastVNC vector and PNG artwork. Requires rsvg-convert and Pillow."""
# SPDX-License-Identifier: GPL-3.0-or-later
from pathlib import Path
import io
import subprocess
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"
BRAND = ROOT / "metadata/en-US/branding"

# All Android and SVG variants share these paths, including the monochrome mark.
SHAPES = [
    ("M49 67H59L60 76H48Z", "metal", None, None),
    ("M43 76H65Q68 76 68 79H40Q40 76 43 76Z", "metal", None, None),
    ("M33 31H75Q83 31 83 39V63Q83 71 75 71H33Q25 71 25 63V39Q25 31 33 31Z", "#1743AF", None, None),
    ("M33 29H75Q83 29 83 37V61Q83 69 75 69H33Q25 69 25 61V37Q25 29 33 29Z", "metal", None, None),
    ("M34 33H74Q79 33 79 38V58Q79 63 74 63H34Q29 63 29 58V38Q29 33 34 33Z", "screen", None, None),
    ("M34 34H74Q78 34 78 38V39Q55 39 30 55V38Q30 34 34 34Z", "#24FFFFFF", None, None),
    ("M42 43H66M60 37L66 43L60 49", None, "#FFFFFF", 3.2),
    ("M66 53H42M48 47L42 53L48 59", None, "#B8F3FF", 3.2),
    ("M52 66H56", None, "#9CB9D9", 1),
]
GRADIENTS = {
    "background": (0, 0, 90, 108, [(0, "#55B9FF"), (.48, "#0875F7"), (1, "#2848D4")]),
    "metal": (34, 29, 67, 80, [(0, "#FFFFFF"), (.55, "#EDF6FF"), (1, "#AFC9EC")]),
    "screen": (31, 34, 76, 63, [(0, "#28B9FA"), (.55, "#087CEC"), (1, "#3454D5")]),
}


def svg_color(color):
    if color.startswith("#") and len(color) == 9:
        return f'"{color[0] + color[3:]}" fill-opacity="{int(color[1:3], 16) / 255:.4f}"'
    return f'"{color}"'


def svg(background=True):
    definitions = []
    for name, (x1, y1, x2, y2, stops) in GRADIENTS.items():
        definitions.append(f'<linearGradient id="{name}" gradientUnits="userSpaceOnUse" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">' +
                           ''.join(f'<stop offset="{offset}" stop-color="{color}"/>' for offset, color in stops) + '</linearGradient>')
    paths = []
    for data, fill, stroke, width in SHAPES:
        fill_attr = '"none"' if fill is None else svg_color(fill) if fill.startswith('#') else f'"url(#{fill})"'
        attrs = f' fill={fill_attr}'
        if stroke:
            attrs += f' stroke="{stroke}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"'
        paths.append(f'<path d="{data}"{attrs}/>')
    base = '<rect width="108" height="108" rx="24" fill="url(#background)"/>' if background else ''
    return '<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108">' + \
           '<title>FastVNC — computer and remote connection</title><defs>' + ''.join(definitions) + '</defs>' + base + ''.join(paths) + '</svg>\n'


def vector_shape(data, fill, stroke, width):
    attrs = f'android:pathData="{data}"'
    if fill in GRADIENTS:
        x1, y1, x2, y2, stops = GRADIENTS[fill]
        return f'<path {attrs}><aapt:attr name="android:fillColor"><gradient android:startX="{x1}" android:startY="{y1}" android:endX="{x2}" android:endY="{y2}" android:type="linear">' + \
               ''.join(f'<item android:offset="{offset}" android:color="{color}"/>' for offset, color in stops) + '</gradient></aapt:attr></path>'
    attrs += f' android:fillColor="{fill or "#00000000"}"'
    if stroke:
        attrs += f' android:strokeColor="{stroke}" android:strokeWidth="{width}" android:strokeLineCap="round" android:strokeLineJoin="round"'
    return f'<path {attrs}/>'


def vector(shapes):
    return '<?xml version="1.0" encoding="utf-8"?>\n<!-- SPDX-License-Identifier: GPL-3.0-or-later; generated by scripts/generate_branding.py -->\n' + \
           '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n' + \
           '\n'.join(vector_shape(*s) for s in shapes) + '\n</vector>\n'


def render(source, size):
    return Image.open(io.BytesIO(subprocess.check_output(
        ["rsvg-convert", "--width", str(size), "--height", str(size)], input=source.encode()))).convert("RGBA")


def main():
    BRAND.mkdir(parents=True, exist_ok=True)
    full = svg()
    (BRAND / "icon.svg").write_text(full)
    render(full, 1024).save(BRAND / "fastvnc-icon-1024.png")
    render(svg(background=False), 1024).save(BRAND / "fastvnc-mark-1024.png")
    # Store artwork is an opaque square; stores/launchers apply their own mask.
    store = full.replace('rx="24"', 'rx="0"')
    render(store, 512).convert("RGB").save(ROOT / "metadata/en-US/images/icon.png")
    (RES / "drawable/ic_launcher_background.xml").write_text(vector([("M0 0H108V108H0Z", "background", None, None)]))
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector(SHAPES))
    mono = [
        ("M33 29H75Q83 29 83 37V61Q83 69 75 69H59L60 76H65Q68 76 68 79H40Q40 76 43 76H48L49 69H33Q25 69 25 61V37Q25 29 33 29Z " +
         "M34 33Q29 33 29 38V58Q29 63 34 63H74Q79 63 79 58V38Q79 33 74 33Z", "#000000", None, None),
        *[(data, None, "#000000", width) for data, _, stroke, width in SHAPES if stroke and width > 1],
    ]
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector(mono))
    for density, size in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
        folder = RES / f"mipmap-{density}"
        folder.mkdir(exist_ok=True)
        render(full, size * 4).resize((size, size), Image.Resampling.LANCZOS).save(folder / "ic_launcher.png")
        rounded = render(store, size * 4)
        mask = Image.new("L", rounded.size)
        ImageDraw.Draw(mask).ellipse((0, 0, rounded.width - 1, rounded.height - 1), fill=255)
        rounded.putalpha(mask)
        rounded.resize((size, size), Image.Resampling.LANCZOS).save(folder / "ic_launcher_round.png")
    # Editable documentation wordmark, independent of system font availability on Android.
    wordmark = f'<svg xmlns="http://www.w3.org/2000/svg" width="720" height="200" viewBox="0 0 720 200"><rect width="720" height="200" rx="32" fill="#F1F5FB"/><svg x="30" y="30" width="140" height="140" viewBox="0 0 108 108">{full.split(">", 1)[1].rsplit("</svg>", 1)[0]}</svg><text x="200" y="118" font-family="-apple-system, BlinkMacSystemFont, Arial, sans-serif" font-size="76" font-weight="600" letter-spacing="-3" fill="#122342">FastVNC</text></svg>\n'
    (BRAND / "wordmark.svg").write_text(wordmark)
    print("FastVNC artwork regenerated from shared vector paths")


if __name__ == "__main__":
    main()
